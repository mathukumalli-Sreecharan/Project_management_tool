import io
import re
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch

def _build_pdf(project_name, doc_title, summary, sections):
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=50, leftMargin=50,
        topMargin=50, bottomMargin=50
    )

    styles = getSampleStyleSheet()
    
    title_style = ParagraphStyle(
        'TitleStyle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=24,
        spaceAfter=20,
        alignment=1 # Center
    )
    
    subtitle_style = ParagraphStyle(
        'SubtitleStyle',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=14,
        textColor=colors.HexColor('#38bdf8'),
        spaceAfter=20,
        alignment=1 # Center
    )
    
    summary_style = ParagraphStyle(
        'SummaryStyle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=11,
        textColor=colors.HexColor('#475569'),
        spaceAfter=40,
        alignment=1 # Center
    )
    
    h1_style = ParagraphStyle('H1', parent=styles['Heading1'], fontName='Helvetica-Bold', fontSize=16, spaceBefore=15, spaceAfter=10)
    h2_style = ParagraphStyle('H2', parent=styles['Heading2'], fontName='Helvetica-Bold', fontSize=14, spaceBefore=12, spaceAfter=8)
    h3_style = ParagraphStyle('H3', parent=styles['Heading3'], fontName='Helvetica-Bold', fontSize=12, spaceBefore=10, spaceAfter=6)
    h4_style = ParagraphStyle('H4', parent=styles['Heading4'], fontName='Helvetica-Bold', fontSize=11, spaceBefore=8, spaceAfter=4)
    normal_style = ParagraphStyle('Norm', parent=styles['Normal'], fontName='Helvetica', fontSize=10, spaceBefore=4, spaceAfter=4)
    list_style = ParagraphStyle('List', parent=styles['Normal'], fontName='Helvetica', fontSize=10, leftIndent=20, spaceBefore=2, spaceAfter=2)
    code_style = ParagraphStyle('Code', parent=styles['Normal'], fontName='Courier', fontSize=9, textColor=colors.HexColor('#334155'), leftIndent=20)
    blockquote_style = ParagraphStyle('Quote', parent=styles['Normal'], fontName='Helvetica-Oblique', fontSize=10, textColor=colors.HexColor('#64748b'), leftIndent=20, rightIndent=20, spaceBefore=8, spaceAfter=8, backColor=colors.HexColor('#f8fafc'), borderPadding=8, borderLeftColor=colors.HexColor('#cbd5e1'), borderLeftWidth=3)

    story = []
    
    # Title Page
    story.append(Spacer(1, 2*inch))
    story.append(Paragraph(str(project_name).upper(), title_style))
    story.append(Paragraph(doc_title, subtitle_style))
    story.append(Paragraph(str(summary), summary_style))
    story.append(Spacer(1, 2*inch))
    story.append(Paragraph("Generated by vilje AI Design Architect", normal_style))
    story.append(PageBreak())

    def parse_markdown_to_flowables(text):
        flowables = []
        if not text:
            return flowables
            
        def format_md(t):
            t = t.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
            t = re.sub(r'!\[([^\]]*)\]\([^\)]+\)', r'<i>[Image: \1]</i>', t)
            t = re.sub(r'\*\*\*(.+?)\*\*\*', r'<b><i>\1</i></b>', t)
            t = re.sub(r'___(.+?)___', r'<b><i>\1</i></b>', t)
            t = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', t)
            t = re.sub(r'__(.+?)__', r'<b>\1</b>', t)
            t = re.sub(r'(?<!\*)\*(?!\*)(.+?)(?<!\*)\*(?!\*)', r'<i>\1</i>', t)
            t = re.sub(r'(?<!_)_(?!_)(.+?)(?<!_)_(?!_)', r'<i>\1</i>', t)
            t = re.sub(r'`([^`]+)`', r'<font name="Courier">\1</font>', t)
            t = re.sub(r'\[([^\]]+)\]\([^\)]+\)', r'<font color="#2563eb"><u>\1</u></font>', t)
            return t
            
        lines = text.splitlines()
        i = 0
        while i < len(lines):
            line = lines[i]
            line_stripped = line.strip()
            
            # Handle Code Blocks
            if line_stripped.startswith('```'):
                code_lines = []
                i += 1
                while i < len(lines) and not lines[i].strip().startswith('```'):
                    # Retain whitespace but escape XML
                    safe_line = lines[i].replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
                    safe_line = safe_line.replace(' ', '&nbsp;')
                    code_lines.append(safe_line)
                    i += 1
                if code_lines:
                    avail_width = letter[0] - 100
                    t = Table([[Paragraph("<br/>".join(code_lines), code_style)]], colWidths=[avail_width])
                    t.setStyle(TableStyle([
                        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#f8fafc')),
                        ('BOX', (0,0), (-1,-1), 1, colors.HexColor('#e2e8f0')),
                        ('TOPPADDING', (0,0), (-1,-1), 8),
                        ('BOTTOMPADDING', (0,0), (-1,-1), 8),
                        ('LEFTPADDING', (0,0), (-1,-1), 10),
                        ('RIGHTPADDING', (0,0), (-1,-1), 10),
                        ('VALIGN', (0,0), (-1,-1), 'TOP')
                    ]))
                    flowables.append(t)
                    flowables.append(Spacer(1, 10))
                i += 1
                continue

            # Handle Tables
            if line_stripped.startswith('|'):
                table_data = []
                while i < len(lines) and lines[i].strip().startswith('|'):
                    row_content = lines[i].strip()
                    if not all(c in '|- ' for c in row_content.strip('|')):
                        cells = [c.strip() for c in row_content.split('|')]
                        if row_content.startswith('|'): cells = cells[1:]
                        if row_content.endswith('|'): cells = cells[:-1]
                        if cells:
                            # We wrap cell text in Paragraphs to allow wrapping
                            table_data.append([Paragraph(format_md(c), normal_style) for c in cells])
                    i += 1
                
                if table_data:
                    num_cols = max(len(r) for r in table_data)
                    avail_width = letter[0] - 100 # 8.5in - 50pt left - 50pt right margins
                    col_width = avail_width / num_cols if num_cols > 0 else avail_width
                    
                    t = Table(table_data, colWidths=[col_width] * num_cols)
                    t.setStyle(TableStyle([
                        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#f1f5f9')),
                        ('TEXTCOLOR', (0, 0), (-1, 0), colors.black),
                        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
                        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
                        ('FONTSIZE', (0, 0), (-1, 0), 10),
                        ('BOTTOMPADDING', (0, 0), (-1, 0), 12),
                        ('BACKGROUND', (0, 1), (-1, -1), colors.white),
                        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#cbd5e1')),
                        ('VALIGN', (0,0), (-1,-1), 'TOP')
                    ]))
                    flowables.append(t)
                    flowables.append(Spacer(1, 10))
                continue
                
            # Headers
            if line.startswith('#### '):
                flowables.append(Paragraph(format_md(line[5:]), h4_style))
            elif line.startswith('### '):
                flowables.append(Paragraph(format_md(line[4:]), h3_style))
            elif line.startswith('## '):
                flowables.append(Paragraph(format_md(line[3:]), h2_style))
            elif line.startswith('# '):
                flowables.append(Paragraph(format_md(line[2:]), h1_style))
            elif line_stripped.startswith('> '):
                flowables.append(Paragraph(format_md(line_stripped[2:]), blockquote_style))
            elif line_stripped in ('---', '***', '___'):
                t = Table([['']], colWidths=[letter[0]-100])
                t.setStyle(TableStyle([('LINEBELOW', (0,0), (-1,-1), 0.5, colors.HexColor('#cbd5e1'))]))
                flowables.append(Spacer(1, 5))
                flowables.append(t)
                flowables.append(Spacer(1, 10))
            elif line_stripped.startswith('- ') or line_stripped.startswith('* '):
                # Handle indented lists
                indent = len(line) - len(line.lstrip())
                prefix = u"\u2022 " if indent < 4 else u"\u25E6 "
                bullet_style = ParagraphStyle('BStyle', parent=list_style, leftIndent=20 + (indent * 5))
                flowables.append(Paragraph(prefix + format_md(line_stripped[2:]), bullet_style))
            elif line_stripped and line_stripped[0].isdigit() and '. ' in line[:5]:
                # List items
                if '->' in line:
                    flowables.append(Paragraph(format_md(line), code_style))
                else:
                    flowables.append(Paragraph(format_md(line), list_style))
            elif line_stripped == "":
                flowables.append(Spacer(1, 5))
            else:
                flowables.append(Paragraph(format_md(line), normal_style))
                
            i += 1
            
        return flowables

    for section_title, section_content in sections:
        if section_content:
            story.append(Paragraph(section_title, h1_style))
            story.append(Spacer(1, 10))
            story.extend(parse_markdown_to_flowables(section_content))
            story.append(PageBreak())

    doc.build(story)
    buffer.seek(0)
    return buffer.read()

def generate_design_pdf(project_name, summary, hld, lld):
    return _build_pdf(
        project_name, 
        "High-Level & Low-Level Design Specification",
        summary,
        [("1. High-Level Design (HLD)", hld), ("2. Low-Level Design (LLD)", lld)]
    )

def generate_hld_pdf(project_name, summary, hld):
    return _build_pdf(
        project_name, 
        "High-Level Design Specification",
        summary,
        [("High-Level Design", hld)]
    )

def generate_lld_pdf(project_name, summary, lld):
    return _build_pdf(
        project_name, 
        "Low-Level Design Specification",
        summary,
        [("Low-Level Design", lld)]
    )
